import workspaceRouter from "./workspace.js";
import {login,getSession,logout} from "../controllers/authController.js";
import {getAdminData,getOverview,previewCpiLink,importRecords,saveRecord,deleteRecord} from "../controllers/researchController.js";
import {health,getPublicData} from "../controllers/publicController.js";
import {rewriteWriteRoute} from "../middleware/rewriteWriteRoute.js";
import {Router} from "express";
import {rateLimit} from "express-rate-limit";
import {auth} from "../middleware/auth.js";
import {publicRouter} from "./public.js";
import {documentRouter} from "./documents.js";
const router=Router();
const loginLimit=rateLimit({windowMs:15*60000,limit:10});
router.get("/api/health", health,
);
router.get("/api/data", getPublicData);
router.post("/api/auth/login", loginLimit, login);
router.get("/api/auth/me", auth, getSession);
router.post("/api/auth/logout", auth, logout);
router.use("/api", documentRouter(auth));
router.use("/api", publicRouter);
router.get("/api/admin/data", auth, getAdminData);
router.get("/api/admin/overview", auth, getOverview);
router.post("/api/admin/cpi/link-preview", auth, previewCpiLink);
router.use("/api/workspace",workspaceRouter);
router.use("/api", rewriteWriteRoute);
router.use("/api/admin", auth);
router.post("/api/admin/:collection/import", importRecords);
router.put("/api/admin/:collection/:key", saveRecord);
router.delete("/api/admin/:collection/:key", deleteRecord);
export default router;
