import {Router} from 'express';
import {rateLimit} from 'express-rate-limit';
import {auth} from '../middleware/auth.js';
import {workspaceStatus,setupWorkspace,createProgramme,saveQuickFee,saveQuickCpi,workspaceData,workspaceReport,seedDemoData} from '../controllers/workspaceController.js';
import {generateExplanation} from '../controllers/aiController.js';
const router=Router();
router.get('/status',workspaceStatus);
router.post('/setup',rateLimit({windowMs:900000,limit:5}),setupWorkspace);
router.use(auth);
router.get('/data',workspaceData);
router.get('/report',workspaceReport);
router.post('/demo-data',seedDemoData);
router.post('/programmes',createProgramme);
router.put('/fees',saveQuickFee);
router.post('/cpi',saveQuickCpi);
router.post('/explain',rateLimit({windowMs:60000,limit:6}),generateExplanation);
export default router;
